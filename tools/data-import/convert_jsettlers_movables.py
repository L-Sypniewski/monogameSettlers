#!/usr/bin/env python3
"""Convert JSettlers' settler animation tables (MIT) into Homestead's data/settlers.json.

Usage: convert_jsettlers_movables.py <settlers-remake checkout> <output file>

Reads jsettlers.graphics/src/main/resources/jsettlers/graphics/map/draw/settlerimages/movables.txt
(shared by all peoples) and movables-<CIV>.txt, expands their templates the way JSettlers'
MovableParser does and writes one rule per line:
[people or null, type, action, material, direction, file, sequence, start, duration].
"*" is a wildcard; a file "cN" stands for the people's file N (10/20/30/40 + N). The more specific
rule wins (see SettlerAnimations); run again to refresh, do not edit the output by hand.
"""
import json
import os
import re
import sys

PEOPLES = ["ROMAN", "EGYPTIAN", "ASIAN", "AMAZON"]
LINE = re.compile(r"\s*([\w*]+)\s*,\s*([\w*]+)\s*,\s*([\w*]+)\s*,\s*([\w*]+)\s*=\s*(c?\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*,\s*(-?\d+)\s*")
EXPRESSION = re.compile(r"\s*(-?\d+)\s*([-+*/%])\s*(-?\d+)\s*")


class Template:
    def __init__(self, declaration):
        # "!NAME a b c {" -> parameter names
        self.parameters = declaration.split()[1:-1]
        self.lines = []

    def invoke(self, arguments, emit):
        variables = dict(zip(self.parameters, arguments))
        for line in self.lines:
            for name, value in variables.items():
                line = line.replace("$" + name, value)
            if line.startswith("%"):
                target, expression = line[1:].split("=", 1)
                a, op, b = EXPRESSION.fullmatch(expression).groups()
                a, b = int(a), int(b)
                variables[target.strip()] = str({"+": a + b, "-": a - b, "*": a * b, "/": a // b, "%": a % b}[op])
            else:
                emit(line)


def parse(path, templates, emit):
    current = None
    with open(path, encoding="utf-8") as f:
        for raw in f:
            line = raw.rstrip("\n")
            if not line or line.startswith("#"):
                continue
            if line.startswith("}"):
                current = None
            elif line.startswith("!"):
                name = line[1:line.index(" ")]
                current = templates[name] = Template(line)
            elif "(" in line:
                # Inside a template definition, a nested call expands into the template's lines.
                name = line[:line.index("(")]
                arguments = line[line.index("(") + 1:line.rindex(")")].split(",")
                templates[name].invoke(arguments, current.lines.append if current else emit)
            elif current is not None:
                current.lines.append(line)
            else:
                emit(line)


def main():
    checkout, output = sys.argv[1], sys.argv[2]
    folder = os.path.join(checkout, "jsettlers.graphics/src/main/resources/jsettlers/graphics/map/draw/settlerimages")
    templates = {}
    rules = []

    def collect(people):
        def emit(line):
            m = LINE.fullmatch(line)
            if not m:
                raise ValueError(f"invalid line: {line}")
            t, a, mat, d, file, seq, start, duration = m.groups()
            rules.append([people, t, a, mat, d, file if file.startswith("c") else int(file), int(seq), int(start), int(duration)])
        return emit

    parse(os.path.join(folder, "movables.txt"), templates, collect(None))
    for people in PEOPLES:
        parse(os.path.join(folder, f"movables-{people}.txt"), templates, collect(people.capitalize()))

    with open(output, "w", encoding="utf-8") as f:
        f.write("{\n")
        f.write('  "_source": "Generated by tools/data-import/convert_jsettlers_movables.py from JSettlers\' movables*.txt (MIT). Do not edit by hand.",\n')
        f.write('  "_format": "[people or null (all), type, action, material, direction, file (cN = people file N), sequence, start, duration]; * = any",\n')
        f.write('  "rules": [\n')
        f.write(",\n".join("    " + json.dumps(r, separators=(",", ":")) for r in rules))
        f.write("\n  ]\n}\n")
    print(f"{len(rules)} rules -> {output}")


if __name__ == "__main__":
    main()
